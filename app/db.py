"""Database connection handling and schema.

Two databases are supported, chosen by environment variables:

- PostgreSQL when DATABASE_URL is set (used in production, e.g. Neon).
- SQLite otherwise, in the file tracker.db or the path in TRACKER_DB (local runs and tests).

The rest of the app writes each query once, with `?` placeholders, and gets rows that work
like dicts (row["id"], dict(row)) from both databases.
"""
import os
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

DEFAULT_DB = Path(__file__).resolve().parent.parent / "tracker.db"

# Raised when a UNIQUE rule is broken (e.g. a taken username), whichever database is in use.
