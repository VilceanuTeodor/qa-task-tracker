def database_url():
    # Set this (e.g. to a Neon connection string) to use PostgreSQL. It contains a password,
    # so it belongs in an environment variable or a git-ignored .env file, never in the code.
    return os.environ.get("DATABASE_URL", "").strip()


def using_postgres():
    return bool(database_url())


def db_path():
    # TRACKER_DB lets tests point the app at a throwaway database.
    return os.environ.get("TRACKER_DB", str(DEFAULT_DB))


class Connection:
    """A thin wrapper so the same SQL runs on both databases."""

    def __init__(self, raw, postgres):
        self._raw = raw
        self._postgres = postgres

    def execute(self, sql, params=()):
        if self._postgres:
            # SQLite uses ? for parameters, PostgreSQL (psycopg) uses %s.
            sql = sql.replace("?", "%s")
        return self._raw.execute(sql, params)


_pool = None
_pool_lock = threading.Lock()


def _postgres_pool():
    """One shared pool of open connections, created on first use.

    Reusing connections matters for a hosted database: opening a new one means a
    network round trip plus TLS setup every time.
    """
    global _pool
    with _pool_lock:
        if _pool is None:
            _pool = ConnectionPool(
                database_url(),
                min_size=1,
                max_size=int(os.environ.get("DB_POOL_SIZE", "5")),
                # dict_row: rows come back as dicts, like sqlite3.Row.
                # prepare_threshold=None: no server-side prepared statements, which
                # keeps it compatible with pooled endpoints such as Neon's (PgBouncer).
                kwargs={"row_factory": dict_row, "prepare_threshold": None},
                # Neon closes idle connections when the database sleeps; check each one before use.
                check=ConnectionPool.check_connection,
                open=True,
            )
        return _pool


@contextmanager
def get_conn():
    """A connection for one unit of work: committed if the block succeeds, rolled back if it raises."""
    if using_postgres():
        with _postgres_pool().connection() as raw:   # commits or rolls back on exit
            yield Connection(raw, postgres=True)
        return

    conn = sqlite3.connect(db_path())
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield Connection(conn, postgres=False)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db():
    if using_postgres():
        with _postgres_pool().connection() as conn:
            for statement in POSTGRES_SCHEMA.split(";"):
                if statement.strip():
                    conn.execute(statement)
    else:
        conn = sqlite3.connect(db_path())
        try:
            conn.executescript(SQLITE_SCHEMA)
        finally:
            conn.close()
